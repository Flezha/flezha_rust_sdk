//! `Change` trait, `NoChange` zero-variant default, and `CoalesceKey`
//! newtype per `relay-state-persistence-rust/design.md` Decisions 3 and 4.
//!
//! The `Change` trait is a marker bounded on
//! `Serialize + DeserializeOwned + Send + Sync + 'static` with one
//! defaulted method: `coalesce_key(&self) -> Option<CoalesceKey>`. The
//! default returns `None`, meaning records are kept verbatim by the
//! per-Partition flusher.
//!
//! `NoChange` is an uninhabited enum used as the trait's default
//! associated-type value. The runtime detects it via `TypeId` and skips
//! flush-buffer registration entirely.

use std::hash::{Hash, Hasher};

use serde::de::DeserializeOwned;
use serde::Serialize;

/// Persistent state-mutation record. Implementors describe one logical
/// change applied to `Shard::State`; the per-Partition flusher serializes
/// these records and hands the bytes to the controller's WAL. Implementations
/// MUST be deterministic against `Shard::apply_change` — replay equality
/// is verified by `ShardTestHarness::replay_equals`.
pub trait Change: Serialize + DeserializeOwned + Send + Sync + 'static {
    /// Coalescing identifier. Records sharing a non-`None` key within a
    /// single linger window collapse to the most recent record. Records
    /// returning `None` are retained verbatim.
    fn coalesce_key(&self) -> Option<CoalesceKey> {
        None
    }
}

/// Uninhabited enum used as the default `Shard::Change`. Detected at
/// relay-build time via `TypeId` so the runtime can skip flush-buffer
/// allocation for Shards that did not opt into persistence.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum NoChange {}

impl Serialize for NoChange {
    fn serialize<S: serde::Serializer>(&self, _: S) -> Result<S::Ok, S::Error> {
        match *self {}
    }
}

impl<'de> serde::Deserialize<'de> for NoChange {
    fn deserialize<D: serde::Deserializer<'de>>(_: D) -> Result<Self, D::Error> {
        Err(serde::de::Error::custom(
            "NoChange is uninhabited; deserialization is structurally unreachable",
        ))
    }
}

impl Change for NoChange {
    fn coalesce_key(&self) -> Option<CoalesceKey> {
        match *self {}
    }
}

/// Binds a state type to the `Change` enum derived from its fields.
/// Generated by `#[derive(flezha::State)]`; a sugared stateful shard reads
/// its `type Change` and `apply_change` from this binding. Hand-written
/// shards do not need it (they declare `Change` directly).
pub trait DerivedState: Sized {
    /// The field-granular change enum generated for this state.
    type Change: Change;

    /// Fold a derived change into the state. Must be deterministic.
    fn apply_change(state: &mut Self, change: &Self::Change);
}

/// Opaque coalescing key. Constructed via `CoalesceKey::from_hash(&value)`
/// for any `Hash` source. The runtime hashes the source value with
/// `DefaultHasher` (SipHash-13) and stores the resulting `u64` so the
/// drain-time coalescer can index a `HashMap<CoalesceKey, _>` without
/// borrowing the record's fields.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct CoalesceKey(u64);

impl CoalesceKey {
    pub fn from_hash<H: Hash>(value: &H) -> Self {
        let mut hasher = std::collections::hash_map::DefaultHasher::new();
        value.hash(&mut hasher);
        Self(hasher.finish())
    }

    /// Internal accessor for the raw 64-bit hash. Exposed for testing and
    /// telemetry; downstream callers should treat the value as opaque.
    #[doc(hidden)]
    pub fn raw(self) -> u64 {
        self.0
    }
}

impl<T: Hash> From<&T> for CoalesceKey {
    fn from(value: &T) -> Self {
        Self::from_hash(value)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn coalesce_key_from_hash_is_stable_for_same_input() {
        let a = CoalesceKey::from_hash(&("M1", 1234u64));
        let b = CoalesceKey::from_hash(&("M1", 1234u64));
        assert_eq!(a, b);
    }

    #[test]
    fn coalesce_key_distinguishes_different_inputs() {
        let a = CoalesceKey::from_hash(&("M1", 1234u64));
        let b = CoalesceKey::from_hash(&("M5", 1234u64));
        assert_ne!(a, b);
    }

    #[test]
    fn no_change_default_coalesce_key_is_unreachable_in_practice() {
        // Cannot construct a NoChange — the impl is structurally
        // unreachable. This test merely documents that the type compiles.
        let _: fn(&NoChange) -> Option<CoalesceKey> = |c| c.coalesce_key();
    }
}
